"""Builds Cub: from world.json, models.py and game.py, the assembly they
make (output/*_gen.s), then sjasmplus on cub.s, for output/cub.z80, a 128K
snapshot, with its SLD.

    python build.py

fast3d, beside Cub in examples/fast3d, is included from there. Its tables
and line blocks are made by its build.py's own writers -- the same files
its build makes -- and kept in its own output/, where the engine includes
them from (write_engine_tables), so that Cub builds whether or not fast3d
has been.
"""
import subprocess
import sys
from pathlib import Path

CUB = Path(__file__).resolve().parent
OUT = CUB / "output"
sys.path.insert(0, str(CUB))
sys.path.insert(0, str(CUB.parent / "scripts"))

import game  # noqa: E402
import models  # noqa: E402
import z80file  # noqa: E402
from fast3d import FAST3D, build as fast3d_build  # noqa: E402

GENERATED = "; Generated by build.py. Do not edit."


def label(model: str) -> str:
    """A model's name as an assembler label."""
    return model.replace("-", "_")


def write_game(path: Path, world: game.World) -> None:
    """game.py's constants, and the state's layout and its value at power on."""
    left, top, right, bottom = game.WINDOW
    lines = [GENERATED, "; From game.py.", "",
             f"VIEW_LEFT\t\t\tEQU\t\t{left}", f"VIEW_TOP\t\t\tEQU\t\t{top}",
             f"VIEW_RIGHT\t\t\tEQU\t\t{right}", f"VIEW_BOTTOM\t\t\tEQU\t\t{bottom}",
             f"VIEW_ROWS\t\t\tEQU\t\t{game.VIEW_ROWS}",
             # fast3d's: defines, as its IFNDEFs test, not labels
             f"\t\t\t\t\tDEFINE\tSCREEN_CENTRE_X {game.CENTRE_X}",
             f"\t\t\t\t\tDEFINE\tSCREEN_CENTRE_Y {game.CENTRE_Y}",
             f"HORIZON_REACH\t\tEQU\t\t{game.HORIZON_REACH}",
             f"VIEW_ATTRIBUTE\t\tEQU\t\t${game.VIEW_ATTRIBUTE:02X}",
             f"PANEL_ATTRIBUTE\t\tEQU\t\t${game.PANEL_ATTRIBUTE:02X}",
             f"EYE_HEIGHT\t\t\tEQU\t\t{game.EYE_HEIGHT}", f"VIEW_DOWN\t\t\tEQU\t\t{game.VIEW_DOWN}",
             f"MAX_STEPS\t\t\tEQU\t\t{game.MAX_STEPS}", ""]
    state = game.start_state(world).pack()
    lines += ["; The game state, as game.STATE_LAYOUT has it."]
    at = 0
    for name, size in game.STATE_LAYOUT:
        lines.append(f"STATE_{name.upper()}\t\tEQU\t\t{at}")
        at += size
    lines += [f"STATE_SIZE\t\t\tEQU\t\t{at}", "",
              "; Its value as the Spectrum starts (game.start_state).", "\t\t\t\t\tMACRO\tPOWER_ON_STATE",
              "\t\t\t\t\tDB\t\t" + ", ".join(f"${b:02X}" for b in state), "\t\t\t\t\tENDM", ""]
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def write_world(path: Path, world: game.World) -> None:
    """The models the world uses, and its objects as fast3d's
    engine/objects.s reads them."""
    names = list(dict.fromkeys(o.model for o in world.objects))
    shapes = {name: models.model(name) for name in names}
    lines = [GENERATED, "; From world.json and models.py.", ""]
    for name in names:
        vertices, edges = shapes[name]
        lines += [f"{label(name)}_vertices:"] + [f"\t\t\t\t\tDB\t\t{x}, {y}, {z}" for x, y, z in vertices]
        lines += fast3d_build.model_block(label(name), vertices, [list(e) for e in edges], [])
    counts = [len(shapes[o.model][0]) for o in world.objects]
    all_edges = sum(len(shapes[o.model][1]) for o in world.objects)
    lines += [f"WORLD_OBJECTS\t\tEQU\t\t{len(world.objects)}",
              f"POINT_PAGES\t\t\tEQU\t\t{fast3d_build.point_pages(counts)}\t\t\t\t; for every object's points at once",
              f"CUT_LINES\t\t\tEQU\t\t{all_edges}\t\t\t\t; room for every edge cut at once", "",
              "; Each object, turned about y alone, with no spin.", "world:"]
    for o in world.objects:
        lines += [f"; {o.name}"] + fast3d_build.object_record(o.position, (0, o.turn, 0), f"{label(o.model)}_model")
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def write_engine_tables() -> None:
    """fast3d's tables and line blocks, which its engine includes from its
    own output/ -- sjasmplus finds them beside the engine before any include
    path. Made as fast3d's build makes them, into Cub's output/, and copied
    there only where they differ: so that they are never ones an older
    fast3d left, and a fast3d build alongside sees them change only then."""
    writers = {"tables_gen.s": fast3d_build.write_tables, "rows_gen.s": fast3d_build.write_rows,
               "lines_gen.s": fast3d_build.write_lines}
    (FAST3D / "output").mkdir(exist_ok=True)
    for name, write in writers.items():
        write(OUT / name)
        made = (OUT / name).read_bytes()
        engines = FAST3D / "output" / name
        if not engines.is_file() or engines.read_bytes() != made:
            engines.write_bytes(made)


def main() -> None:
    OUT.mkdir(exist_ok=True)
    world = game.load_world()
    write_engine_tables()
    write_game(OUT / "game_gen.s", world)
    write_world(OUT / "world_gen.s", world)
    subprocess.run([fast3d_build.find_sjasmplus(), "--nologo", "--sld=output/cub.sld", "--fullpath",
                    "--lst=output/cub.lst", f"-I{FAST3D}", "cub.s"], cwd=CUB, check=True)
    start = fast3d_build.find_label(OUT / "cub.sld", "start")
    banks = (OUT / "cub.banks").read_bytes()
    (OUT / "cub.z80").write_bytes(z80file.snapshot_128k(banks, start, 0x07))
    print(f"Wrote {OUT / 'cub.z80'} (128K, PC {start:04X}) and {OUT / 'cub.sld'}")


if __name__ == "__main__":
    main()
